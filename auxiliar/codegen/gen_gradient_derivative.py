#!/usr/bin/env python3
"""Generates src/physics_ldg_gradient.h: the derivatives of the bulk energy density with respect to
the 15 first derivatives of Q, df/d(d_j Q_c), and to the 5 independent components, df/dQ_c, taken
symbolically from ldg_energy_calculation in src/physics_ldg.h (so every term, L1 to Lq, is included).
The first enter the distortion stress d_i Q_c df/d(d_j Q_c) of the hydrodynamics; both give the exact
gradient of the discrete energy at the surface sites (surface_dynamics variational).
Run from the repository root: python3 auxiliar/codegen/gen_gradient_derivative.py   (needs sympy)
"""
import re, sympy as sp

src = open('src/physics_ldg.h').read()
macros = dict(re.findall(r'#define\s+(\w+)\s+(\w+\[\d+\])', src))
body = src[src.index('ldg_energy_calculation'):]
body = body[body.index('{') + 1:]
expr = body[body.index('return') + 6:body.index(';', body.index('return'))]
expr = re.sub(r'T\(([0-9.eE+-]+)\)', r'\1', expr)

dQ = [sp.Symbol('dQ_%d' % m) for m in range(15)]
QN = [sp.Symbol('QN_%d' % c) for c in range(5)]
names = {}
for name, target in macros.items():
    arr, idx = re.match(r'(\w+)\[(\d+)\]', target).groups()
    if arr == 'dQ': names[name] = dQ[int(idx)]
    elif arr == 'QN': names[name] = QN[int(idx)]
params = ['sigma', 'a', 'bb', 'cc', 'L1', 'L2', 'L3', 'Lq', 'Ls', 'Lq_tilde', 'deltaepslon',
          'elecfieldx', 'elecfieldy', 'elecfieldz']
for p in params: names[p] = sp.Symbol(p)
names['pow'] = lambda x, y: x ** y
f = sp.sympify(expr, locals=names)

derivs = [sp.expand(sp.diff(f, dQ[m])) for m in range(15)]
assert all(not d.has(sp.Symbol('sigma')) for d in derivs)
qderivs = [sp.expand(sp.diff(f, QN[c])) for c in range(5)]

def c(e):
    s = sp.ccode(e)
    s = re.sub(r'dQ_(\d+)', r'dQ[\1]', s)
    return re.sub(r'QN_(\d+)', r'QN[\1]', s)

def function(name, comment, outsize, exprs):
    repl, red = sp.cse(exprs, symbols=sp.numbered_symbols('t'))
    used = sorted({str(s) for d in exprs for s in d.free_symbols} & set(params))
    out = comment + ['MARLICS_HD inline void %s(const BulkParams& P, const double QN[5], const double dQ[15], double out[%d])' % (name, outsize),
                     '{',
                     '  const double ' + ', '.join('%s=P.%s' % (p, p) for p in used) + ';']
    for s, e in repl:
        out.append('  const double %s=%s;' % (s, c(e)))
    for m, e in enumerate(red):
        out.append('  out[%d]=%s;' % (m, c(e)))
    print('%s: %d common subexpressions, parameters %s' % (name, len(repl), used))
    return out + ['}', '']

out = ['#ifndef PHYSICS_LDG_GRADIENT_H', '#define PHYSICS_LDG_GRADIENT_H',
       '// Generated by auxiliar/codegen/gen_gradient_derivative.py from ldg_energy_calculation (physics_ldg.h).',
       '// Do not edit by hand.',
       '#include "physics.h"', '']
out += function('ldg_gradient_derivative',
                ['//out[5*j+c] = df/d(d_j Q_c), the derivative of the bulk energy density with respect to the',
                 '//first derivative of the independent component c of Q along j.'], 15, derivs)
out += function('ldg_value_derivative',
                ['//out[c] = df/dQ_c at fixed first derivatives, c the independent components.'], 5, qderivs)
out += ['#endif', '']
open('src/physics_ldg_gradient.h', 'w').write('\n'.join(out))
